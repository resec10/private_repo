let currentLang = 'en';

/** CLDR plural category for whole numbers: en one/other, ro one/few/other, ru one/few/many. */
function pluralCategory(lang, n) {
  n = Math.abs(n);
  if (lang === 'ru') {
    const m10 = n % 10;
    const m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return 'one';
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 'few';
    return 'many';
  }
  if (lang === 'ro') {
    if (n === 1) return 'one';
    if (n === 0 || (n % 100 >= 1 && n % 100 <= 19)) return 'few';
    return 'other';
  }
  return n === 1 ? 'one' : 'other';
}

function t(key, params = {}, lang = currentLang) {
  let msg = MESSAGES[lang] && MESSAGES[lang][key] !== undefined ? MESSAGES[lang][key] : MESSAGES.en[key];
  if (msg === undefined) return key;
  if (typeof msg === 'object') msg = msg[pluralCategory(lang, params.n)];
  return msg.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m));
}

/** First supported language in the phone/browser preferences, else English. */
function detectLang(preferred = (self.navigator && self.navigator.languages) || []) {
  for (const tag of preferred) {
    const code = String(tag).toLowerCase().split(/[-_]/)[0];
    if (code === 'mo') return 'ro'; // old code for Romanian (Moldova)
    if (code in LANGUAGES) return code;
  }
  return 'en';
}

function setLang(lang) {
  currentLang = lang in LANGUAGES ? lang : 'en';
}
